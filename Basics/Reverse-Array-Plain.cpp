void reverseArray(int array[], int n){

    int first = 0;
    int last = n - 1;

    while (first <= last) { 
        swap(array[first], array[last]);
        first++;
        last--;
    }
}


int main() {
    int n;
    cout << "Enter number of elements: ";
    cin >> n;

    int arr[n];
    cout << "Enter " << n << " elements: ";
    for (int i = 0; i < n; i++) {
        cin >> arr[i];
    }

    reverseArray(arr, n);

    for (int i = 0; i < n; i++) {
        cout << arr[i] << " ";
    }
    cout << endl;

    return 0;
}
